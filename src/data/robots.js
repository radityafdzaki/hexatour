export const robotsFor = (bodyId) => ROBOTS.filter((r) => r.bodies.includes(bodyId));

const KM_PER_AU = 149597870.7;
const LIGHT_KM_PER_HOUR = 299792.458 * 3600;

// Straight-line estimate from the Horizons range and range rate.
export function distanceNow(h, now = Date.now()) {
  const seconds = (now - h.epoch) / 1000;
  const km = h.rangeAu * KM_PER_AU + h.rateKmS * seconds;
  return { km, au: km / KM_PER_AU, lightHours: km / LIGHT_KM_PER_HOUR };
}
